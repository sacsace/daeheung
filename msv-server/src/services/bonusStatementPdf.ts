import fs from 'fs';
import path from 'path';

export type BonusStatementInput = {
  companyName: string;
  employeeName: string;
  employeeNumber: string;
  department: string;
  fiscalYear: string;
  installment: number;
  installmentsPerYear: number;
  hireDate: string;
  monthsWorked: number;
  monthlySalary: number;
  ratePercent: number;
  amount: number;
};

function resolveFont(): string | null {
  const candidates = [
    path.join(process.cwd(), 'assets', 'fonts', 'NotoSansKR-Regular.otf'),
    path.join(process.cwd(), 'assets', 'fonts', 'NotoSansKR-Regular.ttf'),
    path.join(__dirname, '..', '..', 'assets', 'fonts', 'NotoSansKR-Regular.otf'),
    'C:\\Windows\\Fonts\\malgun.ttf',
    '/usr/share/fonts/truetype/noto/NotoSansKR-Regular.ttf',
    '/usr/share/fonts/opentype/noto/NotoSansKR-Regular.otf',
  ];
  return candidates.find((file) => fs.existsSync(file)) || null;
}

function inr(amount: number): string {
  const n = Math.round(Number(amount) || 0);
  return `INR ${n.toLocaleString('en-IN')}`;
}

function drawLine(doc: any, y: number) {
  doc.save();
  doc.strokeColor('#B4B4B4').lineWidth(0.6).moveTo(48, y).lineTo(547, y).stroke();
  doc.restore();
}

function writePage(doc: any, input: BonusStatementInput, unicode: boolean) {
  const text = (value: string) => {
    const raw = String(value || '').trim() || '-';
    return unicode ? raw : raw.replace(/[^\x20-\x7E]/g, '?');
  };
  const roundLabel =
    input.installmentsPerYear === 2
      ? `${input.installment} of 2`
      : '1 of 1';

  doc.fontSize(16).text('BONUS STATEMENT', 48, 48, { align: 'center', width: 499 });
  doc.fontSize(11).text(text(input.companyName), 48, 74, { align: 'center', width: 499 });
  drawLine(doc, 96);

  const rows: Array<[string, string]> = [
    ['Employee', text(input.employeeName)],
    ['Employee No.', text(input.employeeNumber)],
    ['Department', text(input.department)],
    ['Hire date', text(input.hireDate)],
    ['Fiscal year', text(input.fiscalYear)],
    ['Installment', roundLabel],
    ['Months worked in FY', String(input.monthsWorked)],
    ['Monthly salary', inr(input.monthlySalary)],
    ['Rate', `${Number(input.ratePercent || 0).toFixed(2)}%`],
    ['Bonus amount', inr(input.amount)],
  ];

  let y = 114;
  for (const [label, value] of rows) {
    doc.fontSize(10).fillColor('#334155').text(label, 48, y, { width: 180 });
    doc.fillColor('#0F172A').text(value, 240, y, { width: 300 });
    y += 22;
  }
  drawLine(doc, y + 6);
  doc.fontSize(9).fillColor('#475569').text(
    'Amounts follow the saved bonus rate and payment for this fiscal year. This statement is generated by MVS.',
    48,
    y + 18,
    { width: 499 }
  );
}

export function buildBonusStatementPdf(pages: BonusStatementInput[]): Promise<Buffer> {
  const PDFDocument = require('pdfkit');
  const fontPath = resolveFont();
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 48 });
    const chunks: Buffer[] = [];
    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    let unicode = false;
    if (fontPath) {
      try {
        doc.registerFont('BonusSans', fontPath);
        doc.font('BonusSans');
        unicode = true;
      } catch {
        doc.font('Helvetica');
      }
    } else {
      doc.font('Helvetica');
    }
    pages.forEach((page, index) => {
      if (index > 0) doc.addPage();
      if (unicode) doc.font('BonusSans');
      else doc.font('Helvetica');
      writePage(doc, page, unicode);
    });
    doc.end();
  });
}

import { PAYSLIP_LABELS_EN } from '../payslipLabelsEn';
import { money, type PayslipDocumentView, type PayslipLabels } from '../PayslipContent';
import type { PayrollGridRow } from './payrollGridTypes';

export type BonusStatementSource = {
  employee_id: number;
  employee_name: string;
  employee_number: string;
  department: string;
  email: string;
  bank_account: string;
  bank_ifsc: string;
  hire_date: string | null;
  months_worked: number;
  monthly_salary: number;
  rate_percent: number;
  amount: number;
};

export const BONUS_STATEMENT_LABELS: PayslipLabels = {
  ...PAYSLIP_LABELS_EN,
  title: 'Bonus Statement',
  payrollBadge: 'BONUS',
  salaryStatement: 'Bonus Statement',
  period: 'Fiscal Year',
  workingMonth: 'Fiscal Year',
  paidDays: 'Installment',
  earningsAndDeductions: 'Bonus',
  earnings: 'Bonus',
  grossSalary: 'Bonus',
  netPay: 'Bonus Payable',
  autoGenerated: 'This bonus statement was generated automatically.',
};

function installmentLabel(installment: number, times: 1 | 2) {
  return times === 2 ? `${installment} of 2` : '1 of 1';
}

export function bonusStatementRow(source: BonusStatementSource, fiscalYear: string): PayrollGridRow {
  return {
    id: source.employee_id,
    row_no: source.employee_id,
    emp_id: source.employee_number || '',
    bank_account: source.bank_account || '',
    ifsc: source.bank_ifsc || '',
    bank_name: '',
    employee_email: source.email || '',
    department: source.department || '',
    employee_name: source.employee_name || '',
    position: '',
    birth_date: '',
    joining_date: source.hire_date || '',
    working_month: fiscalYear,
    basic_salary: 0,
    house_rent_allowance: 0,
    other_allowance: 0,
    food_allowance: 0,
    total_salary: source.monthly_salary,
    total_day_of_month: '',
    unpaid_leave: '',
    days_worked: '',
    ot_rate: 0,
    day_ot_hour: 0,
    night_ot_hour: 0,
    transport_allowance: 0,
    overtime: 0,
    sum_total: source.amount,
    pf_employee: '0',
    pf_employer: '0',
    esic_employee: '0',
    esic_employer: '0',
    tds: 0,
    pt: '0',
    deduct_this_month: 0,
    net_salary_payable: source.amount,
  };
}

export function bonusStatementView(
  source: BonusStatementSource,
  fiscalYear: string,
  installment: number,
  times: 1 | 2
): PayslipDocumentView {
  const rate = `${Number(source.rate_percent || 0).toFixed(2)}%${times === 2 ? ' x 50%' : ''}`;
  return {
    headerStats: [
      { label: 'Fiscal Year', value: fiscalYear },
      { label: 'Installment', value: installmentLabel(installment, times) },
    ],
    fields: [
      { label: 'Employee ID', value: source.employee_number },
      { label: 'Department', value: source.department },
      { label: 'Date of Joining', value: source.hire_date, dateOnly: true },
      { label: 'Email', value: source.email, link: true },
      { label: 'Months in FY', value: String(source.months_worked ?? 0) },
      { label: 'Bonus Rate', value: rate, highlight: true },
      { label: 'Monthly Salary', value: money(source.monthly_salary) },
      { label: 'Account Number', value: source.bank_account },
      { label: 'IFSC', value: source.bank_ifsc },
    ],
    earningItems: [
      {
        label: times === 2 ? 'Bonus (50% share)' : 'Bonus',
        value: money(source.amount),
        highlight: true,
      },
    ],
    deductionItems: [{ label: 'Deductions', value: money(0) }],
    grossPay: source.amount,
    totalDeductions: 0,
    netPay: source.amount,
  };
}
